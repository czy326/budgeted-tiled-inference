#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
DOTA labelTxt layout  ->  ultralytics YOLO-OBB layout.

In  : <layout>/{train,val,test}/images/*.png + labelTxt/*.txt
      label row = "x1 y1 x2 y2 x3 y3 x4 y4 <class> <difficult>"   (DOTA, absolute px)
Out : <out>/images/{split}/*.png, <out>/labels/{split}/*.txt, <out>/data.yaml
      label row = "<cls> x1 y1 x2 y2 x3 y3 x4 y4"                 (normalized 0-1)

Why a separate script instead of pointing ultralytics at the existing layout:
ultralytics derives a label path by swapping ``/images/`` for ``/labels/`` and
requires normalized coordinates, so the DOTA files cannot be read as-is.

Degenerate polygons are dropped and counted, never silently kept: a zero-area
or out-of-range polygon makes ultralytics raise mid-training, and a silently
dropped instance would change the label statistics without showing up anywhere.
"""

import argparse
import json
import os
import shutil
import sys

import numpy as np
from PIL import Image

CLASSES = ["ship"]
MIN_AREA_PX = 1.0


def link_or_copy(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if os.path.exists(dst):
        os.remove(dst)
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def parse_row(line):
    """-> (pts (4,2) float, cls_name, difficult int) or None."""
    parts = line.split()
    if len(parts) < 9:
        return None
    try:
        pts = np.array([float(v) for v in parts[0:8]], np.float64).reshape(4, 2)
    except ValueError:
        return None
    return pts, parts[8], int(float(parts[9])) if len(parts) > 9 else 0


def poly_area(pts):
    x, y = pts[:, 0], pts[:, 1]
    return 0.5 * abs(np.dot(x, np.roll(y, 1)) - np.dot(y, np.roll(x, 1)))


def convert_split(layout, out, split, drop_difficult=False, min_area=MIN_AREA_PX):
    src_img = os.path.join(layout, split, "images")
    src_lbl = os.path.join(layout, split, "labelTxt")
    if not os.path.isdir(src_img):
        return None

    dst_img = os.path.join(out, "images", split)
    dst_lbl = os.path.join(out, "labels", split)
    os.makedirs(dst_img, exist_ok=True)
    os.makedirs(dst_lbl, exist_ok=True)

    st = {"images": 0, "instances": 0, "empty": 0, "bad_row": 0,
          "degenerate": 0, "difficult": 0, "out_of_range": 0, "unknown_cls": 0}

    for name in sorted(x for x in os.listdir(src_img) if x.lower().endswith(".png")):
        stem = os.path.splitext(name)[0]
        ip = os.path.join(src_img, name)
        lp = os.path.join(src_lbl, stem + ".txt")
        with Image.open(ip) as im:                     # header only, cheap
            W, H = im.size

        rows_out = []
        if os.path.isfile(lp):
            with open(lp, "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    r = parse_row(line)
                    if r is None:
                        st["bad_row"] += 1
                        continue
                    pts, cls, diff = r
                    if drop_difficult and diff:
                        st["difficult"] += 1
                        continue
                    if cls not in CLASSES:
                        st["unknown_cls"] += 1
                        continue
                    if poly_area(pts) < min_area:
                        st["degenerate"] += 1
                        continue
                    n = pts.copy()
                    n[:, 0] /= float(W)
                    n[:, 1] /= float(H)
                    if (n < 0).any() or (n > 1).any():
                        st["out_of_range"] += 1
                        n = np.clip(n, 0.0, 1.0)
                    c = CLASSES.index(cls)
                    rows_out.append("%d " % c + " ".join("%.6f" % v for v in n.reshape(-1)))

        link_or_copy(ip, os.path.join(dst_img, name))
        with open(os.path.join(dst_lbl, stem + ".txt"), "w", encoding="utf-8") as f:
            f.write("\n".join(rows_out) + ("\n" if rows_out else ""))
        st["images"] += 1
        st["instances"] += len(rows_out)
        if not rows_out:
            st["empty"] += 1
    return st


def write_yaml(out, splits, absolute=False):
    """
    ``path`` is deliberately omitted by default.

    ultralytics resolves relative entries against the directory holding the
    yaml when ``path`` is absent, so the same file works from Windows
    (E:/...) and from WSL (/mnt/e/...). Writing an absolute path here would
    pin the dataset to one of the two and fail silently on the other.
    """
    lines = ["# generated by to_yolo_obb.py -- do not edit by hand"]
    if absolute:
        lines.append("path: %s" % os.path.abspath(out).replace("\\", "/"))
    for s in splits:
        lines.append("%s: images/%s" % (s, s))
    lines.append("names:")
    for i, c in enumerate(CLASSES):
        lines.append("  %d: %s" % (i, c))
    p = os.path.join(out, "data.yaml")
    with open(p, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return p


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--layout", required=True, help="dir holding frame_index.json")
    ap.add_argument("--out", required=True)
    ap.add_argument("--splits", default="train,val,test")
    ap.add_argument("--drop-difficult", action="store_true",
                    help="drop difficult=1 instances (DOTA eval ignores them; "
                         "YOLO has no such concept)")
    args = ap.parse_args(argv)

    if not os.path.isfile(os.path.join(args.layout, "frame_index.json")):
        sys.exit("no frame_index.json in %s -- wrong layout dir?" % args.layout)

    splits = [s.strip() for s in args.splits.split(",") if s.strip()]
    os.makedirs(args.out, exist_ok=True)
    total = None
    for s in splits:
        st = convert_split(args.layout, args.out, s, args.drop_difficult)
        if st is None:
            print("[to_yolo_obb] %-5s : absent, skipped" % s)
            continue
        print("[to_yolo_obb] %-5s : %d images, %d instances%s"
              % (s, st["images"], st["instances"],
                 ", %d empty" % st["empty"] if st["empty"] else ""))
        for k in ("bad_row", "degenerate", "out_of_range", "unknown_cls", "difficult"):
            if st[k]:
                print("            %-13s %d (dropped)" % (k, st[k]))
        total = st if total is None else {k: total[k] + st[k] for k in total}

    p = write_yaml(args.out, splits)
    print("[to_yolo_obb] yaml -> %s" % p)
    if total:
        print("[to_yolo_obb] TOTAL images=%d instances=%d dropped=%d"
              % (total["images"], total["instances"],
                 total["bad_row"] + total["degenerate"] + total["difficult"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
